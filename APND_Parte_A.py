#Guardar informacion fija de un libro que no deberia modificarse accidentalmente.
#Para guardar informacion que no requiera modificaciones accidentales utilizaria una TUPLA (), ya que de todas las estructuras de datos que vimos (listas, matrices, tuplas, conjuntos y diccionarios) es la unica que una vez creada no nos permite modificar su contenido.


# Situacion 3:
#Evitar que un mismo socio aparezca registrado varias veces.
#Utilizaria un CONJUNTO(SET) {}, ya que si principal caracteristica es que no permite que un mismo dato/valor aparezca repetido, los eliminara de de manera automatica.


